"""Summarize human exclusion by normed query membership and relative rank.

The primary summary weights trigger-query items equally within each context
and then weights contexts equally. Pooled response proportions are retained
separately as a denominator check, not substituted for the primary means.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

import numpy as np
import pandas as pd


PIPELINE = Path(__file__).resolve().parents[1]
CURRENT_RESULTS = PIPELINE / "results/set_variant_qwen_corrected_rnx_contrastive_2026-10-23"
CONDITIONS = [("inside", "above"), ("inside", "below"),
              ("outside", "above"), ("outside", "below")]
STRUCTURE_LABELS = {
    ("inside", "above"): "All four",
    ("inside", "below"): "Set, Disjunction",
    ("outside", "above"): "Ordering, Disjunction",
    ("outside", "below"): "None",
}
KEYS = ["story", "cleaned_trigger", "cleaned_query"]


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def check_saved_rates(items: pd.DataFrame, source: Path) -> None:
    saved = pd.read_csv(source)
    saved = saved.loc[saved.dataset.eq("focus_alternative_study")]
    matched = items.merge(
        saved, left_on=KEYS, right_on=["context_id", "trigger", "query"],
        how="outer", validate="one_to_one", indicator=True,
        suffixes=("_computed", "_saved"),
    )
    assert len(matched) == 480 and matched._merge.eq("both").all()
    np.testing.assert_array_equal(matched.n_exclusions, matched.human_yes)
    np.testing.assert_array_equal(matched.n_responses, matched.human_total)
    np.testing.assert_allclose(
        matched.human_rate_computed, matched.human_rate_saved, rtol=0, atol=1e-14,
    )


def manuscript_fragment(summary: pd.DataFrame) -> str:
    indexed = summary.set_index(["set", "scale"])
    rates = {key: float(indexed.loc[key, "mean_item_exclusion_rate"]) for key in CONDITIONS}
    ia, ib, oa, ob = (rates[key] for key in CONDITIONS)
    table_rows = "\n".join(
        f"{STRUCTURE_LABELS[membership, rank]} & {rates[membership, rank]:.3f} & "
        f"{int(indexed.loc[(membership, rank), 'n_pairs'])} " + r"\\"
        for membership, rank in CONDITIONS
    )
    return (
        "% Insert at the beginning of the Focus Alternative Results subsection.\n"
        "% Structures here apply categorically to the independent norming.\n"
        "% Descriptive human results; no fitted model predictions or significance tests.\n"
        "% Generated by summarize_focus_human_conditions.py from the full 3,408-response sample.\n\n"
        "\\paragraph{Human exclusion judgments.}\n"
        "We grouped human judgments according to which alternative structures predict "
        "exclusion when applied categorically to the independently normed alternatives "
        "described in Section~2.1. "
        f"Mean exclusion was {ia:.3f} where all four structures predict exclusion and "
        f"{ob:.3f} where none does (Table~\\ref{{tab:human-focus-conditions}}). "
        "The diagnostic cases distinguish Set from Ordering. "
        f"Exclusion averaged {ib:.3f} where Set and Disjunction predict exclusion but "
        "Ordering and Conjunction do not. Conversely, exclusion averaged "
        f"{oa:.3f} where Ordering and Disjunction predict exclusion but Set and "
        "Conjunction do not. "
        "We calculated exclusion rates for each trigger--query pair, averaged these "
        "equally within each condition and context, and then averaged equally across "
        "the 16 contexts. Thus, listeners excluded alternatives in both cases that "
        "distinguish Set and Ordering, with a higher mean in the case supported by Set. "
        "These graded judgments provide the behavioral target for the probabilistic "
        "models evaluated below.\n\n"
        "\\begin{table}[t]\n\\centering\n\\small\n"
        "\\begin{tabular}{lrr}\n\\hline\n"
        "Structures predicting exclusion & Exclusion & Pairs " + r"\\" + "\n\\hline\n"
        + table_rows + "\n\\hline\n\\end{tabular}\n"
        "\\caption{Human exclusion grouped by the categorical predictions of the "
        "alternative structures applied to the independent norming. All four refers "
        "to Set, Ordering, Conjunction, and Disjunction; None means that none of these "
        "four structures predicts exclusion. These groups are not the predictions "
        "of the fitted probabilistic models. Values are equal-context means of item "
        "exclusion rates. Each "
        "condition contains 852 responses from 213 participants across 16 contexts. "
        "The number of distinct trigger--query pairs differs by condition; every "
        "context contributes 12, 3, 3, and 12 pairs to the four rows, respectively. "
        "The 3,408 responses cover all 480 pairs. "
        "These are descriptive means.}\n"
        "\\label{tab:human-focus-conditions}\n\\end{table}\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--human-data", type=Path,
                        default=PIPELINE / "human_exp_data/sca_dataframe.csv")
    parser.add_argument("--canonical-data", type=Path,
                        default=PIPELINE / "canonical_data/novel_focus_observations.csv")
    parser.add_argument("--source-snapshot", type=Path,
                        default=CURRENT_RESULTS / "inputs/source_rows.csv")
    parser.add_argument("--output-dir", type=Path,
                        default=PIPELINE / "diagnostics/human_focus_conditions_2026-10-26")
    parser.add_argument("--tex-output", type=Path)
    args = parser.parse_args()

    human = pd.read_csv(args.human_data)
    assert len(human) == 3408 and human.id.nunique() == 213
    assert human.story.nunique() == 16 and not human.duplicated(["id", "story"]).any()
    assert set(human.neg) == {0, 1} and human.neg.eq(-human.response).all()
    assert human["set"].eq(np.where(human.query_relevance < 3, "inside", "outside")).all()
    assert human.scale.eq(np.where(
        human.query_relevance < human.trigger_relevance, "above", "below",
    )).all()
    assert human.groupby("id").size().eq(16).all()
    assert human.groupby(["id", "set", "scale"]).size().eq(4).all()

    # Membership and ordering derive from the independent norming, not responses.
    for column in ["set", "scale", "trigger_relevance", "query_relevance"]:
        assert human.groupby(KEYS)[column].nunique().eq(1).all()
    trigger_ranks = human[["story", "cleaned_trigger", "trigger_relevance"]].drop_duplicates()
    query_ranks = human[["story", "cleaned_query", "query_relevance"]].drop_duplicates()
    ranks = trigger_ranks.merge(
        query_ranks, left_on=["story", "cleaned_trigger"],
        right_on=["story", "cleaned_query"], validate="one_to_one",
    )
    assert len(ranks) == 96 and ranks.trigger_relevance.eq(ranks.query_relevance).all()
    assert trigger_ranks.groupby("story").trigger_relevance.apply(
        lambda values: set(values) == set(range(6))
    ).all()

    items = human.groupby(
        KEYS + ["set", "scale", "trigger_relevance", "query_relevance"], as_index=False,
    ).agg(n_exclusions=("neg", "sum"), n_responses=("neg", "size"))
    items["human_rate"] = items.n_exclusions / items.n_responses
    assert len(items) == 480
    check_saved_rates(items, args.canonical_data)
    check_saved_rates(items, args.source_snapshot)

    contexts = items.groupby(["story", "set", "scale"], as_index=False).agg(
        mean_item_exclusion_rate=("human_rate", "mean"),
        n_pairs=("human_rate", "size"), n_exclusions=("n_exclusions", "sum"),
        n_responses=("n_responses", "sum"),
    )
    expected_counts = {("inside", "above"): 12, ("inside", "below"): 3,
                       ("outside", "above"): 3, ("outside", "below"): 12}
    for key, expected in expected_counts.items():
        rows = contexts.loc[contexts["set"].eq(key[0]) & contexts.scale.eq(key[1])]
        assert len(rows) == 16 and rows.n_pairs.eq(expected).all()
    summary = contexts.groupby(["set", "scale"]).agg(
        mean_item_exclusion_rate=("mean_item_exclusion_rate", "mean"),
        n_contexts=("story", "size"), n_pairs=("n_pairs", "sum"),
        n_exclusions=("n_exclusions", "sum"), n_responses=("n_responses", "sum"),
    ).reindex(CONDITIONS).reset_index()
    summary["pooled_response_exclusion_rate"] = summary.n_exclusions / summary.n_responses
    summary["n_participants"] = human.id.nunique()
    summary["set_predicts_exclusion"] = summary["set"].eq("inside")
    summary["ordering_predicts_exclusion"] = summary.scale.eq("above")
    summary["conjunction_predicts_exclusion"] = (
        summary.set_predicts_exclusion & summary.ordering_predicts_exclusion
    )
    summary["disjunction_predicts_exclusion"] = (
        summary.set_predicts_exclusion | summary.ordering_predicts_exclusion
    )
    summary["structures_predicting_exclusion"] = [
        STRUCTURE_LABELS[membership, rank]
        for membership, rank in zip(summary["set"], summary.scale)
    ]
    assert summary.n_responses.eq(852).all()
    # Cell sizes are identical across contexts, so equal-context and equal-item means agree.
    item_means = items.groupby(["set", "scale"]).human_rate.mean().reindex(CONDITIONS)
    np.testing.assert_allclose(summary.mean_item_exclusion_rate, item_means, rtol=0, atol=1e-14)

    args.output_dir.mkdir(parents=True, exist_ok=True)
    outputs = []
    for name, data in [("condition_summary.csv", summary),
                       ("context_condition_summary.csv", contexts),
                       ("item_condition_rates.csv", items)]:
        path = args.output_dir / name
        data.to_csv(path, index=False)
        outputs.append(path)
    if args.tex_output:
        args.tex_output.parent.mkdir(parents=True, exist_ok=True)
        args.tex_output.write_text(manuscript_fragment(summary))
        outputs.append(args.tex_output)
    provenance = {
        "sources": [{"path": str(p.resolve()), "sha256": sha256(p)} for p in
                    [args.human_data, args.canonical_data, args.source_snapshot]],
        "script": {"path": str(Path(__file__).resolve()), "sha256": sha256(Path(__file__))},
        "responses": len(human), "participants": int(human.id.nunique()),
        "contexts": int(human.story.nunique()), "items": len(items),
        "primary_aggregation": "mean item rates within condition/context, then equal-context mean",
        "diagnostic_aggregation": "sum exclusions / sum responses; separate pooled-response column",
        "classification": "inside: query norm rank 0-2; above: query rank < trigger rank",
        "structure_mapping": "categorical rules applied to independent norming; not fitted probabilistic predictions",
        "validation": "all 480 counts/rates match canonical data and active corrected snapshot",
        "inference": "descriptive; no significance tests or uncertainty intervals computed",
        "outputs": [{"path": str(p.resolve()), "sha256": sha256(p)} for p in outputs],
    }
    (args.output_dir / "provenance.json").write_text(json.dumps(provenance, indent=2) + "\n")
    print(summary.to_string(index=False))
    print(f"Validated 480 item rates; saved summaries to {args.output_dir.resolve()}")


if __name__ == "__main__":
    main()
